"""Shared configuration for the velocity-control numerical experiments."""

from dataclasses import dataclass
from typing import Callable

from obj_func import Quad_arith, Rosenbrock, Dixon_price, Powell, Qing


@dataclass(frozen=True)
class ProblemSpec:
    key: str
    title: str
    result_prefix: str
    default_dim: int
    use_nag: bool
    factory: Callable


PROBLEMS = {
    "quad_arith": ProblemSpec(
        key="quad_arith",
        title="Quadratic function",
        result_prefix="Quad_arith",
        default_dim=1_000_000,
        use_nag=True,
        factory=Quad_arith,
    ),
    "rosenbrock": ProblemSpec(
        key="rosenbrock",
        title="Rosenbrock",
        result_prefix="Rosenbrock",
        default_dim=1_000_000,
        use_nag=False,
        factory=Rosenbrock,
    ),
    "dixon_price": ProblemSpec(
        key="dixon_price",
        title="Dixon-Price",
        result_prefix="Dixon_price",
        default_dim=1_000_000,
        use_nag=False,
        factory=Dixon_price,
    ),
    "powell": ProblemSpec(
        key="powell",
        title="Powell",
        result_prefix="Powell",
        default_dim=1_000_000,
        use_nag=False,
        factory=Powell,
    ),
    "qing": ProblemSpec(
        key="qing",
        title="Qing",
        result_prefix="Qing",
        default_dim=100_000,
        use_nag=False,
        factory=Qing,
    ),
}

# Algorithms run by --algorithms auto.
BASE_ALGORITHMS = ("gd", "hb", "agd", "ours")

# Keep the paper runner and plotter on exactly the same experiment grid.
VC_COMPARE_R = 0.5
VC_COMPARE_ALPHA = 0.1
VC_SWEEP_RS = (0.25, 0.5, 0.75)
VC_SWEEP_ALPHAS = (0.05, 0.1, 0.5)
VC_PAPER_LINE_SEARCH_MODE = "parallel"
VC_PAPER_COMPARE_ALGORITHMS = ("ours", "ours_defer_cp")
VC_PAPER_LABELS = {"ours": "VC", "ours_defer_cp": "Predictive VC"}
VC_PAPER_REPEATS = 10


def problem_choices():
    return tuple(PROBLEMS.keys())


def get_problem_spec(problem):
    return PROBLEMS[problem]


def default_algorithms(problem):
    algorithms = list(BASE_ALGORITHMS)
    if PROBLEMS[problem].use_nag:
        algorithms.append("nag")
    if problem == "powell":
        algorithms.append("nagc")
    return algorithms


def make_model(problem, dim=None, L=10_000, sigma_x0=1.0, seed=0):
    spec = PROBLEMS[problem]
    dim = spec.default_dim if dim is None else dim

    if problem == "quad_arith":
        return spec.factory(n=dim, L=L)
    if problem == "powell" and dim % 4 != 0:
        raise ValueError("Powell requires --dim to be divisible by 4.")
    return spec.factory(d=dim, sigma_x0=sigma_x0, seed=seed)


def result_filename(problem, algorithm, R=None, alpha=None, line_search_mode="parallel", checkpoint_threshold=None):
    """Return the filename generated by optimizer.py for one experiment."""
    prefix = PROBLEMS[problem].result_prefix
    suffixes = {
        "gd": "_gd.npz",
        "hb": "_restartHB.npz",
        "agd": "_restartAGD.npz",
        "nag": "_nagsc.npz",
        "nagc": "_nagc.npz",
    }
    if algorithm in {"ours", "ours_cp", "ours_defer_r", "ours_defer_cp"}:
        if R is None or alpha is None:
            raise ValueError(f"R and alpha are required for algorithm={algorithm!r}.")
        suffix = "" if line_search_mode == "parallel" else "_short"
        if algorithm == "ours":
            return f"{prefix}R{R}a{alpha}_adavelocontrol{suffix}.npz"
        if algorithm == "ours_defer_r":
            return f"{prefix}R{R}a{alpha}_adavelocontrol_deferR{suffix}.npz"
        if checkpoint_threshold is None:
            raise ValueError(
                "checkpoint_threshold is required for checkpoint VC variants."
            )
        if algorithm == "ours_defer_cp":
            return (
                f"{prefix}R{R}a{alpha}_adavelocontrol_deferR_"
                f"cpT{int(checkpoint_threshold)}{suffix}.npz"
            )
        return f"{prefix}R{R}a{alpha}_adavelocontrol_cpT{int(checkpoint_threshold)}{suffix}.npz"
    return prefix + suffixes[algorithm]
